import AppKit

/// Plain-data copy of every pasteboard item and representation. Lives in memory only.
public struct PasteboardSnapshot: Sendable, Equatable {
    public struct Entry: Sendable, Equatable {
        public var type: String
        public var data: Data
        public init(type: String, data: Data) { self.type = type; self.data = data }
    }

    public var items: [[Entry]]
    public var changeCount: Int

    public init(items: [[Entry]], changeCount: Int) {
        self.items = items
        self.changeCount = changeCount
    }

    public var byteCount: Int { items.joined().reduce(0) { $0 + $1.data.count } }

    /// Plain text of the first item that has any, for display only.
    public var plainText: String? { Self.plainText(of: items) }

    static func plainText(of items: [[Entry]]) -> String? {
        for entries in items {
            func data(_ type: String) -> Data? { entries.first { $0.type == type }?.data }
            if let data = data(PasteboardTypes.plainUTF8), let text = String(data: data, encoding: .utf8) { return text }
            if let data = data(PasteboardTypes.plainUTF16External), let text = String(data: data, encoding: .utf16) { return text }
            if let data = data(PasteboardTypes.plainUTF16), let text = String(data: data, encoding: .utf16LittleEndian) { return text }
            for entry in entries where PasteboardTypes.rtf.contains(entry.type) || PasteboardTypes.rtfd.contains(entry.type) {
                let type: NSAttributedString.DocumentType = PasteboardTypes.rtf.contains(entry.type) ? .rtf : .rtfd
                if let text = try? NSAttributedString(data: entry.data, options: [.documentType: type], documentAttributes: nil) {
                    return text.string
                }
            }
        }
        return nil
    }
}

public enum ClipboardContent: Sendable, Equatable {
    case empty
    /// Contains text we can clean.
    case text
    /// Marked concealed/transient by its source (password managers): never read.
    case protected
    /// Files, images or other non-text content.
    case other
}

public enum PasteboardTypes {
    public static let plainUTF8 = "public.utf8-plain-text"
    public static let plainUTF16External = "public.utf16-external-plain-text"
    public static let plainUTF16 = "public.utf16-plain-text"
    public static let rtf: Set<String> = ["public.rtf", "NeXT Rich Text Format v1.0 pasteboard type"]
    public static let rtfd: Set<String> = ["com.apple.flat-rtfd", "NeXT RTFD pasteboard type"]
    public static let html: Set<String> = ["public.html", "Apple HTML pasteboard type"]
    public static let webArchive = "com.apple.webarchive"
    public static let source = "org.nspasteboard.source"
    /// https://nspasteboard.org markers for content that must not be inspected or stored.
    public static let protected: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.apple.is-remote-clipboard.concealed",
    ]

    static let plain: Set<String> = [plainUTF8, plainUTF16External, plainUTF16]
    static let cleanable: Set<String> = plain.union(rtf).union(rtfd).union(html)

    public static func classify(_ types: [String]?) -> ClipboardContent {
        guard let types, !types.isEmpty else { return .empty }
        if types.contains(where: protected.contains) { return .protected }
        if types.contains(where: cleanable.contains) { return .text }
        return .other
    }
}

public struct PasteboardCleaningResult: Sendable, Equatable {
    public var items: [[PasteboardSnapshot.Entry]]
    public var removedCount: Int
    public var replacedCount: Int
    public var changed: Bool { removedCount + replacedCount > 0 }
    public var plainText: String? { PasteboardSnapshot.plainText(of: items) }
}

/// Pure transformation of a snapshot. Safe to run off the main thread.
public enum PasteboardTextCleaner {
    /// - Parameter progress: called with the fraction of bytes processed, ending at 1.
    public static func process(
        _ snapshot: PasteboardSnapshot, options: CleaningOptions, progress: (@Sendable (Double) -> Void)? = nil
    ) -> PasteboardCleaningResult {
        var removed = 0, replaced = 0
        let total = max(snapshot.byteCount, 1)
        var done = 0
        let items = snapshot.items.map { entries -> [PasteboardSnapshot.Entry] in
            let item = processItem(entries, options: options) { bytes in
                done += bytes
                progress?(min(Double(done) / Double(total), 1))
            }
            removed += item.removed
            replaced += item.replaced
            return item.entries
        }
        progress?(1)
        return PasteboardCleaningResult(items: items, removedCount: removed, replacedCount: replaced)
    }

    private static func processItem(
        _ entries: [PasteboardSnapshot.Entry], options: CleaningOptions, processed: (Int) -> Void
    ) -> (entries: [PasteboardSnapshot.Entry], removed: Int, replaced: Int) {
        var removed = 0, replaced = 0, richChanged = false
        var output: [PasteboardSnapshot.Entry] = []

        for entry in entries {
            defer { processed(entry.data.count) }
            guard let cleaned = clean(entry, options: options) else {
                output.append(entry)
                continue
            }
            // The item reports the largest change across its representations, not their sum.
            removed = max(removed, cleaned.removed)
            replaced = max(replaced, cleaned.replaced)
            if !PasteboardTypes.plain.contains(entry.type) { richChanged = true }
            output.append(PasteboardSnapshot.Entry(type: entry.type, data: cleaned.data))
        }
        if richChanged {
            // Web archives embed the same marked HTML and cannot be rewritten safely; the
            // cleaned HTML/RTF representations replace them.
            output.removeAll { $0.type == PasteboardTypes.webArchive }
        }
        return (output, removed, replaced)
    }

    /// Returns nil when the entry is not text we handle, or when nothing changed.
    private static func clean(
        _ entry: PasteboardSnapshot.Entry, options: CleaningOptions
    ) -> (data: Data, removed: Int, replaced: Int)? {
        let type = entry.type
        if type == PasteboardTypes.plainUTF8 {
            return cleanString(entry.data, encoding: .utf8, options: options)
        }
        if type == PasteboardTypes.plainUTF16External {
            return cleanString(entry.data, encoding: .utf16, options: options)
        }
        if type == PasteboardTypes.plainUTF16 {
            return cleanString(entry.data, encoding: .utf16LittleEndian, options: options)
        }
        if PasteboardTypes.rtf.contains(type) {
            return cleanAttributed(entry.data, documentType: .rtf, options: options)
        }
        if PasteboardTypes.rtfd.contains(type) {
            return cleanAttributed(entry.data, documentType: .rtfd, options: options)
        }
        if PasteboardTypes.html.contains(type) {
            return cleanHTML(entry.data, options: options)
        }
        return nil
    }

    private static func cleanString(
        _ data: Data, encoding: String.Encoding, options: CleaningOptions
    ) -> (data: Data, removed: Int, replaced: Int)? {
        guard let text = String(data: data, encoding: encoding) else { return nil }
        let result = TextCleaner.clean(text, options: options)
        guard result.changed, let output = result.text.data(using: encoding) else { return nil }
        return (output, result.removedCount, result.replacedCount)
    }

    /// Edits the attributed string in place so fonts, links and attachments survive.
    /// Untouched rich text is never re-encoded.
    private static func cleanAttributed(
        _ data: Data, documentType: NSAttributedString.DocumentType, options: CleaningOptions
    ) -> (data: Data, removed: Int, replaced: Int)? {
        let readOptions: [NSAttributedString.DocumentReadingOptionKey: Any] = [.documentType: documentType]
        var attributes: NSDictionary?
        guard let text = try? NSMutableAttributedString(data: data, options: readOptions, documentAttributes: &attributes)
        else { return nil }
        let edits = TextCleaner.edits(in: text.string, options: options)
        guard !edits.isEmpty else { return nil }
        TextCleaner.apply(edits, to: text)

        var writeAttributes = (attributes as? [NSAttributedString.DocumentAttributeKey: Any]) ?? [:]
        writeAttributes[.documentType] = documentType
        guard let output = try? text.data(from: NSRange(location: 0, length: text.length),
                                          documentAttributes: writeAttributes)
        else { return nil }
        let removed = edits.lazy.filter { $0.replacement.isEmpty }.count
        return (output, removed, edits.count - removed)
    }

    /// Cleans literal characters in the markup (tags and attributes are ASCII and unaffected)
    /// plus character references to code points that are never legitimate.
    private static func cleanHTML(
        _ data: Data, options: CleaningOptions
    ) -> (data: Data, removed: Int, replaced: Int)? {
        guard let html = String(data: data, encoding: .utf8) else { return nil }
        var htmlOptions = options
        htmlOptions.keepNoBreakSpace = true
        let result = TextCleaner.clean(html, options: htmlOptions)
        let (text, removedReferences) = stripCharacterReferences(result.text)
        guard result.changed || removedReferences > 0, let output = text.data(using: .utf8) else { return nil }
        return (output, result.removedCount + removedReferences, result.replacedCount)
    }

    static func stripCharacterReferences(_ html: String) -> (String, Int) {
        guard html.contains("&"), let referencePattern = try? NSRegularExpression(
            pattern: "&(?:#[xX]([0-9A-Fa-f]{1,6})|#([0-9]{1,7})|(shy|ZeroWidthSpace|NoBreak));"
        ) else { return (html, 0) }
        let source = html as NSString
        var result = ""
        var cursor = 0
        var count = 0
        for match in referencePattern.matches(in: html, range: NSRange(location: 0, length: source.length)) {
            let codePoint: UInt32?
            if match.range(at: 1).location != NSNotFound {
                codePoint = UInt32(source.substring(with: match.range(at: 1)), radix: 16)
            } else if match.range(at: 2).location != NSNotFound {
                codePoint = UInt32(source.substring(with: match.range(at: 2)))
            } else {
                codePoint = ["shy": 0x00AD, "ZeroWidthSpace": 0x200B, "NoBreak": 0x2060][source.substring(with: match.range(at: 3))]
            }
            guard let codePoint, UnicodeTables.isContextFreeStrip(codePoint) else { continue }
            result += source.substring(with: NSRange(location: cursor, length: match.range.location - cursor))
            cursor = NSMaxRange(match.range)
            count += 1
        }
        guard count > 0 else { return (html, 0) }
        result += source.substring(from: cursor)
        return (result, count)
    }
}
